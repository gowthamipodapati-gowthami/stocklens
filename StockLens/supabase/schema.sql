-- StockLens: run in Supabase SQL Editor (or any PostgreSQL 14+ database).
-- No public Supabase/anon privileges are granted to these tables.
-- The FastAPI server connects with its secret PostgreSQL connection URL.

CREATE TABLE IF NOT EXISTS public.stocks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'USD',
    source VARCHAR(32) NOT NULL DEFAULT 'yahoo_finance',
    last_refreshed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_stocks_symbol ON public.stocks(symbol);

CREATE TABLE IF NOT EXISTS public.daily_prices (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_id INTEGER NOT NULL REFERENCES public.stocks(id) ON DELETE CASCADE,
    trading_date DATE NOT NULL,
    open DOUBLE PRECISION NOT NULL,
    high DOUBLE PRECISION NOT NULL,
    low DOUBLE PRECISION NOT NULL,
    close DOUBLE PRECISION NOT NULL,
    volume BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_price_stock_day UNIQUE(stock_id, trading_date)
);
CREATE INDEX IF NOT EXISTS ix_daily_prices_stock_date
    ON public.daily_prices(stock_id, trading_date);

CREATE TABLE IF NOT EXISTS public.forecast_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_id INTEGER NOT NULL REFERENCES public.stocks(id) ON DELETE CASCADE,
    as_of_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    horizon_days INTEGER NOT NULL CHECK (horizon_days BETWEEN 1 AND 90),
    model_name VARCHAR(120) NOT NULL,
    mae DOUBLE PRECISION NOT NULL,
    baseline_mae DOUBLE PRECISION NOT NULL,
    rmse DOUBLE PRECISION NOT NULL,
    validation_points INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_forecast_run_stock_asof
    ON public.forecast_runs(stock_id, as_of_date);

CREATE TABLE IF NOT EXISTS public.forecast_points (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES public.forecast_runs(id) ON DELETE CASCADE,
    step INTEGER NOT NULL,
    trading_date DATE NOT NULL,
    predicted_close DOUBLE PRECISION NOT NULL,
    lower_bound DOUBLE PRECISION NOT NULL,
    upper_bound DOUBLE PRECISION NOT NULL,
    CONSTRAINT uq_forecast_run_step UNIQUE(run_id, step)
);

-- Frontend never queries Supabase directly. No anon/authenticated policies.
ALTER TABLE public.stocks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_prices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.forecast_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.forecast_points ENABLE ROW LEVEL SECURITY;
-- No Supabase Data API access is needed; only the privately connected FastAPI
-- database role reads/writes the tables. These grants may differ by project.
REVOKE ALL ON TABLE public.stocks, public.daily_prices,
    public.forecast_runs, public.forecast_points FROM anon, authenticated;
